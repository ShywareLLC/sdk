// Transport dispatch, not a local ledger decorator. The receiving server
// discards dummy envelopes before calling canonical services.
export const DISPATCH_BYTES = 32768;
const encoder = new TextEncoder();

export function encodeDispatch(kind, body) {
  if (!['dummy', 'cast', 'update'].includes(kind)) throw new Error('Invalid dispatch kind');
  const json = JSON.stringify({ version: 1, kind, body });
  const length = encoder.encode(json).length;
  if (length > DISPATCH_BYTES) throw new Error('Dispatch body exceeds fixed envelope size');
  return json + ' '.repeat(DISPATCH_BYTES - length);
}

/**
 * One request per active scheduled slot. Real operations occupy slots instead
 * of creating extra requests. send must perform the HTTP request to /dispatch
 * for both real and dummy bodies, using the same authentication policy.
 * This does not conceal plaintext from the receiving server, other endpoints,
 * TLS headers, response timing, or an application's start/stop behavior.
 */
export class CoverTrafficDispatcher {
  constructor(send, { ratePerMinute = 10, maxPending = 64, onCoverError = () => {} } = {}) {
    if (typeof send !== 'function') throw new Error('A network transport is required');
    if (!Number.isFinite(ratePerMinute) || ratePerMinute < 0.01 || ratePerMinute > 600) throw new Error('Invalid cover traffic rate');
    if (!Number.isInteger(maxPending) || maxPending < 1) throw new Error('Invalid queue capacity');
    this.send = send;
    this.intervalMs = 60000 / ratePerMinute;
    this.maxPending = maxPending;
    this.onCoverError = onCoverError;
    this.queue = [];
    this.timer = null;
    this.inFlight = new Set();
  }

  submit(kind, body) {
    const encoded = encodeDispatch(kind, body);
    if (kind === 'dummy') throw new Error('Dummies are generated by scheduled slots');
    if (!this.timer) throw new Error('Cover traffic is not running');
    if (this.queue.length >= this.maxPending) throw new Error('Cover traffic queue is full');
    return new Promise((resolve, reject) => this.queue.push({ encoded, resolve, reject }));
  }

  // Also exposed for deterministic schedule tests; callers must not create
  // additional activity-triggered ticks in production.
  tick() {
    const queued = this.queue.shift();
    const encoded = queued?.encoded ?? encodeDispatch('dummy', { tx: '' });
    const task = Promise.resolve().then(() => this.send(encoded)).then(result => {
      if (queued) queued.resolve(result);
    }, error => {
      if (queued) queued.reject(error);
      else this.onCoverError(error);
    });
    this.inFlight.add(task);
    task.finally(() => this.inFlight.delete(task));
    return task;
  }

  start() {
    if (this.timer) return;
    this.timer = setInterval(() => { this.tick(); }, this.intervalMs);
  }

  stop() {
    clearInterval(this.timer);
    this.timer = null;
    for (const queued of this.queue.splice(0)) queued.reject(new Error('Cover traffic stopped before dispatch'));
    // Already dispatched operations retain their outcomes. Never retry an
    // uncertain canonical write automatically.
  }
}
